"""Persian subtitle generation (SubStation Alpha) for FFmpeg/libass.

libass performs the Persian shaping and bidi reordering at render time
(built with HarfBuzz+FriBidi on Debian); this module only emits a correct
ASS document:

- UTF-8 ``PlayResX/PlayResY`` matching the output canvas
- a bottom-centred RTL-friendly style using a Persian-capable font
- per-segment timing derived from segment weights (character counts)
"""

from __future__ import annotations

import re
from dataclasses import dataclass

MAX_LINE_CHARS = 90
MIN_SEGMENT_SECONDS = 1.2


@dataclass(frozen=True)
class SubtitleSegment:
    text: str
    start_seconds: float
    end_seconds: float


def _clean_text(text: str) -> str:
    # ASS braces are override blocks; strip them to avoid injection into the
    # subtitle stream. Newlines collapse to spaces.
    text = re.sub(r"[{}]", "", text)
    return re.sub(r"\s+", " ", text).strip()


def split_into_segments(text: str, *, max_chars: int = MAX_LINE_CHARS) -> list[str]:
    """Split Persian narration into subtitle-sized chunks on sentence/clause
    boundaries (Persian sentence marks respected)."""
    cleaned = _clean_text(text)
    if not cleaned:
        return []
    sentences = re.split(r"(?<=[.!?؟،؛:])\s+", cleaned)
    segments: list[str] = []
    buffer = ""
    for sentence in sentences:
        if not sentence:
            continue
        if len(sentence) > max_chars:
            # hard-wrap very long sentences on spaces
            words = sentence.split(" ")
            for word in words:
                candidate = f"{buffer} {word}".strip()
                if len(candidate) > max_chars and buffer:
                    segments.append(buffer)
                    buffer = word
                else:
                    buffer = candidate
            continue
        candidate = f"{buffer} {sentence}".strip()
        if len(candidate) > max_chars and buffer:
            segments.append(buffer)
            buffer = sentence
        else:
            buffer = candidate
    if buffer:
        segments.append(buffer)
    return segments


def build_segments(
    text: str, total_seconds: float, *, max_chars: int = MAX_LINE_CHARS
) -> list[SubtitleSegment]:
    """Distribute *total_seconds* across segments weighted by text length."""
    chunks = split_into_segments(text, max_chars=max_chars)
    if not chunks or total_seconds <= 0:
        return []
    weights = [max(len(chunk), 1) for chunk in chunks]
    total_weight = sum(weights)
    segments: list[SubtitleSegment] = []
    cursor = 0.0
    for index, chunk in enumerate(chunks):
        share = total_seconds * (weights[index] / total_weight)
        start = cursor
        end = total_seconds if index == len(chunks) - 1 else cursor + max(share, 0.0)
        # guarantee a visible minimum
        if end - start < MIN_SEGMENT_SECONDS and index < len(chunks) - 1:
            end = start + MIN_SEGMENT_SECONDS
        segments.append(SubtitleSegment(text=chunk, start_seconds=round(start, 3), end_seconds=round(end, 3)))
        cursor = end
    return segments


def _ass_time(seconds: float) -> str:
    seconds = max(0.0, seconds)
    hours = int(seconds // 3600)
    minutes = int((seconds % 3600) // 60)
    secs = seconds % 60
    return f"{hours}:{minutes:02d}:{secs:05.2f}"


def build_ass_subtitle(
    segments: list[SubtitleSegment],
    *,
    width: int,
    height: int,
    font_name: str = "Vazirmatn",
    font_size: int | None = None,
    primary_color: str = "&H00FFFFFF",
    outline_color: str = "&H00101010",
) -> str:
    """Emit an ASS subtitle document for Persian (RTL) rendering via libass."""
    size = font_size or max(28, height // 40)
    margin_v = max(int(height * 0.06), 40)
    header = f"""[Script Info]
; Generated by Vandad Agent — Persian (fa-IR) subtitles
ScriptType: v4.00+
PlayResX: {width}
PlayResY: {height}
ScaledBorderAndShadow: yes
WrapStyle: 0

[V4+ Styles]
Format: Name, Fontname, Fontsize, PrimaryColour, SecondaryColour, OutlineColour, BackColour, Bold, Italic, Underline, StrikeOut, ScaleX, ScaleY, Spacing, Angle, BorderStyle, Outline, Shadow, Alignment, MarginL, MarginR, MarginV, Encoding
Style: Persian,{font_name},{size},{primary_color},&H000000FF,{outline_color},&H80000000,0,0,0,0,100,100,0,0,1,3,1,2,60,60,{margin_v},1

[Events]
Format: Layer, Start, End, Style, Name, MarginL, MarginR, MarginV, Effect, Text
"""
    lines = [
        f"Dialogue: 0,{_ass_time(seg.start_seconds)},{_ass_time(seg.end_seconds)},Persian,,0,0,0,,{seg.text}"
        for seg in segments
    ]
    return header + "\n".join(lines) + "\n"


def build_ass_for_script(
    script_text: str,
    *,
    total_seconds: float,
    width: int,
    height: int,
    font_name: str = "Vazirmatn",
) -> str:
    segments = build_segments(script_text, total_seconds)
    return build_ass_subtitle(segments, width=width, height=height, font_name=font_name)
